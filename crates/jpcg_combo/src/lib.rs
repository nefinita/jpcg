// ============================================================================
// jpcg_combo — 连招计算引擎（jpcg_core 体系的子模块）
//
// 职责边界（与 core 的分工）：
//   core      — 单技能伤害公式（JpcgConfig）、追加真伤公式（已损失×系数）、
//               数据/预设存储 —— 所有"核心计算"。
//   combo     — 连招编排：每步伤害组合、血量推进（实际扣血）、
//               追加真伤按步结算、击杀率（蒙特卡洛采样）、击杀曲线。
//
// 计算模型（双通道）：
//   期望通道  — 每步 g/h/q/dot 期望、累计期望/方差（与旧 kill_prob 语义一致）。
//   蒙特卡洛  — samples 条随机路径（会心逐技能/dot 逐跳独立判定），
//               真伤按路径实时血量结算，击杀率 = 击杀路径占比。
// ============================================================================

pub mod conv;
pub mod engine;
pub mod ffi;
pub mod host;

/// 本 combo 模块库版本（与 FFI jpcg_combo_version 一致）
pub const COMBO_VERSION: &str = env!("CARGO_PKG_VERSION");

